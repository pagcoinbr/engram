#!/usr/bin/env python3
"""memory_index_build.py — DETERMINISTICALLY generate MEMORY.md from the memory
files' own frontmatter, under a byte budget, ranked by fixation score.

Why: the hand-maintained flat index overflowed its session-load limit and was
pruned by hand — leaving ~49 memories unlinked and invisible at session start,
while stale/auto sections accreted. This regenerates the whole index from the
source of truth (each file's `name`/`description`/`type`) so nothing is ever
orphaned, the file stays under the load budget forever, and the fixation score
finally has a consumer: trusted memories earn their place, low-value ones spill
into a collapsed "+N more" line (still recallable via memory_recall_hybrid).

No LLM. Pure function of the files on disk + .fixation_state.json.

Ranking:
  * `user` and `feedback` memories are ALWAYS included (identity + rules).
  * `project` / `reference` / `snippet` are ranked by fixation last_score, then
    mtime, and filled until the byte budget is hit; the remainder collapse to one
    line.

Usage:
  memory_index_build.py                 # print generated index to stdout (dry-run)
  memory_index_build.py --write         # atomically replace MEMORY.md (under the index lock)
  memory_index_build.py --budget N      # byte budget (default 16000)
"""
from __future__ import annotations
import fcntl
import json
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path.home() / ".claude"))
import engram_secrets

HOME = Path.home()
SLUG = os.environ.get("CLAUDE_MEMORY_SLUG") or str(HOME).replace("/", "-")
MEM_DIR = HOME / ".claude" / "projects" / SLUG / "memory"
INDEX = MEM_DIR / "MEMORY.md"
LOCK = INDEX.with_suffix(".md.lock")
STATE = MEM_DIR / ".fixation_state.json"

DEFAULT_BUDGET = int(os.environ.get("MEMORY_INDEX_BUDGET", "17000"))
DESC_MAX = 60
# Reserve for structural lines the fill loop doesn't price in (section headers,
# blank separators, per-type "+N more" notes, footer) so the final file stays
# under budget rather than overshooting it.
STRUCT_RESERVE = 600

# type -> (section title, always_include, order)
SECTIONS = [
    ("user",      "Who I am (user)",   True,  0),
    ("feedback",  "How to work (feedback)", True, 1),
    ("project",   "Projects",          False, 2),
    ("reference", "References",         False, 3),
    ("snippet",   "Snippets (code that worked)", False, 4),
]


def _frontmatter(text: str) -> dict:
    """name/description + metadata.type, tolerating both frontmatter conventions."""
    fm = {}
    if not text.startswith("---"):
        return fm
    end = text.find("\n---", 3)
    block = text[3:end] if end != -1 else text[3:]
    for key in ("name", "description"):
        m = re.search(rf"^{key}:\s*(.+)$", block, re.M)
        if m:
            fm[key] = m.group(1).strip().strip('"').strip()
    t = re.search(r"^\s*type:\s*(\w+)", block, re.M)  # matches top-level or metadata.type
    if t:
        fm["type"] = t.group(1).strip()
    return fm


def _scores() -> dict:
    try:
        return {k: (v.get("last_score") or 0.0)
                for k, v in json.loads(STATE.read_text()).get("memories", {}).items()}
    except Exception:
        return {}


def collect():
    scores = _scores()
    items = []
    for p in sorted(MEM_DIR.glob("*.md")):
        if p.name == "MEMORY.md":
            continue
        fm = _frontmatter(p.read_text(errors="ignore"))
        typ = fm.get("type") if fm.get("type") in {s[0] for s in SECTIONS} else "reference"
        # Redact the name/description before they land in MEMORY.md (which gets
        # pushed to GitHub) — a pre-existing secret in frontmatter must not be
        # published via the index.
        desc = re.sub(r"\s+", " ", engram_secrets.redact(fm.get("description", ""))[0]).strip()
        if len(desc) > DESC_MAX:
            desc = desc[:DESC_MAX - 1].rstrip() + "…"
        items.append({
            "file": p.name,
            "name": engram_secrets.redact(fm.get("name", p.stem))[0],
            "desc": desc,
            "type": typ,
            "score": float(scores.get(p.name, 0.0)),
            "mtime": p.stat().st_mtime,
        })
    return items


def _line(it):
    tail = f" — {it['desc']}" if it["desc"] else ""
    return f"- [{it['name']}]({it['file']}){tail}"


def build(budget=DEFAULT_BUDGET):
    items = collect()
    always_types = {t for t, _, a, _ in SECTIONS if a}
    header = ["# Memory Index",
              "_Generated by memory_index_build.py — do not hand-edit (regenerated on write)._",
              ""]
    used = len("\n".join(header)) + 80  # + footer margin

    # Always-include groups (user/feedback) are reserved first.
    selected = {t: [] for t, *_ in SECTIONS}
    for it in items:
        if it["type"] in always_types:
            selected[it["type"]].append(it)
            used += len(_line(it)) + 1

    # Rank ALL remaining (project+reference) in ONE global pool by score then
    # recency, and fill until the budget — so neither type is starved by the
    # other's ordering. Dropped counts are tallied per type for the "+N more" note.
    pool = sorted((it for it in items if it["type"] not in always_types),
                  key=lambda x: (x["score"], x["mtime"]), reverse=True)
    dropped = {t: 0 for t, *_ in SECTIONS}
    fill_ceiling = budget - STRUCT_RESERVE
    for it in pool:
        ln = len(_line(it)) + 1
        if used + ln <= fill_ceiling:
            selected[it["type"]].append(it)
            used += ln
        else:
            dropped[it["type"]] += 1

    out = list(header)
    shown = 0
    for typ, title, _, _ in SECTIONS:
        group = selected[typ]
        if not group and not dropped[typ]:
            continue
        group.sort(key=lambda x: (x["score"], x["mtime"]), reverse=True)
        out.append(f"## {title}")
        for it in group:
            out.append(_line(it)); shown += 1
        if dropped[typ]:
            out.append(f"- _+{dropped[typ]} more {typ} memories below the index budget — "
                       f"recall with `memory_recall_hybrid`._")
        out.append("")

    out.append(f"<!-- {shown}/{len(items)} memories linked; generated deterministically. -->")
    return "\n".join(out).rstrip() + "\n"


def main():
    args = sys.argv[1:]
    budget = DEFAULT_BUDGET
    if "--budget" in args:
        budget = int(args[args.index("--budget") + 1])
    content = build(budget)
    if "--write" not in args:
        sys.stdout.write(content)
        return
    MEM_DIR.mkdir(parents=True, exist_ok=True)
    # Hold the SAME advisory lock the bash writers use, so a concurrent
    # save_memory.sh add-line can't interleave with our full replace.
    with open(LOCK, "a") as lk:
        try:
            fcntl.flock(lk, fcntl.LOCK_EX)
        except Exception:
            pass
        tmp = INDEX.with_suffix(".md.tmp")
        tmp.write_text(content)
        tmp.replace(INDEX)
    sys.stderr.write(f"[index-build] wrote {INDEX} ({len(content)} bytes)\n")


if __name__ == "__main__":
    main()
